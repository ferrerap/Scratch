#!/usr/bin/env python3
"""Side-by-side comparison of Reviewer A and B positions at proposition level.
Usage: python3 -I scripts/compare_positions.py <A.json> <B.json> <out.md>
Accepts either a bare positions array or an object with a "positions" key.
"""
import json, sys, re

def load(p):
    d = json.load(open(p, encoding="utf-8"))
    return d["positions"] if isinstance(d, dict) else d

A, B, OUT = load(sys.argv[1]), load(sys.argv[2]), sys.argv[3]
def key(p):
    m = re.match(r"(P\d\.\d|P-NEW[^ ]*|[A-Z]{2}\d{2,3}|K\d{3})", str(p.get("proposition_id", "")))
    return m.group(1) if m else str(p.get("proposition_id"))
ia = {key(p): p for p in A}
ib = {key(p): p for p in B}
keys = sorted(set(ia) | set(ib))
lines = ["# Round 2 — proposition-level comparison (Reviewer A vs Reviewer B)", "",
         "Generated by `scripts/compare_positions.py`. Overlap = evidence IDs cited as support by one reviewer and acknowledged as adverse by the other (or cited by both).", ""]
for k in keys:
    a, b = ia.get(k, {}), ib.get(k, {})
    sa = set(a.get("supporting_evidence_ids") or []); sb = set(b.get("supporting_evidence_ids") or [])
    aa = set(a.get("adverse_evidence_ids_acknowledged") or []); ab = set(b.get("adverse_evidence_ids_acknowledged") or [])
    lines.append(f"## {k}")
    lines.append(f"- **A:** {a.get('position_summary','(no position)')}")
    lines.append(f"  - holds if: {a.get('holds_under_conditions','')}")
    lines.append(f"  - support: {', '.join(sorted(sa))} | adverse acknowledged: {', '.join(sorted(aa))}")
    lines.append(f"  - would change view if: {a.get('would_change_my_view_if','')}")
    lines.append(f"- **B:** {b.get('position_summary','(no position)')}")
    lines.append(f"  - holds if: {b.get('holds_under_conditions','')}")
    lines.append(f"  - support: {', '.join(sorted(sb))} | adverse acknowledged: {', '.join(sorted(ab))}")
    lines.append(f"  - would change view if: {b.get('would_change_my_view_if','')}")
    lines.append(f"- shared support IDs: {', '.join(sorted(sa & sb)) or 'none'}; A-support acknowledged adverse by B: {', '.join(sorted(sa & ab)) or 'none'}; B-support acknowledged adverse by A: {', '.join(sorted(sb & aa)) or 'none'}")
    lines.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("propositions:", len(keys))
