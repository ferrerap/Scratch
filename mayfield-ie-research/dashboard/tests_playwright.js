const { chromium } = require('playwright');
const path = require('path');
const file = 'file://' + path.resolve(process.argv[2]);
const out = process.argv[3];
const D = require(path.resolve(process.argv[4]));
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  const reqs = [];
  page.on('request', r => { if (!r.url().startsWith('file:')) reqs.push(r.url()); });
  await page.goto(file);
  const results = [];
  const check = (name, ok, info='') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name} ${info}`);
  // overview
  const stats = await page.$$eval('#stats .stat b', els => els.map(e => e.textContent));
  check('stats match data', JSON.stringify(stats) === JSON.stringify([D.meta.counts.firms, D.meta.counts.priority, D.meta.counts.evidence, D.meta.counts.audit, D.meta.counts.sources, D.meta.counts.segments].map(String)), stats.join(','));
  const order = await page.evaluate(() => { const m = document.querySelector('#matrix'), f = document.querySelector('#findings'); return !!(m.compareDocumentPosition(f) & Node.DOCUMENT_POSITION_FOLLOWING); });
  check('landscape matrix appears before findings', order);
  const lg = await page.$$eval('#legend dt', d => d.map(x => x.textContent));
  check('legend defines every strength row and position column', lg.length === D.legend.strength.length + D.legend.positions.length && D.legend.strength.length === 6 && D.legend.positions.length === 6, lg.length);
  const rowNames = await page.$$eval('#matrix tbody th', t => t.map(x => x.textContent));
  check('every matrix row has a legend definition', rowNames.every(r => D.legend.strength.some(x => x.level === r)), rowNames.join('|'));
  const chips = await page.$$eval('#matrix .chip', els => els.length);
  check('matrix shows all firms', chips === D.firms.length, chips);
  await page.screenshot({ path: out + '/01_overview.png', fullPage: true });
  // evidence trails on principal findings
  const nf = await page.$$eval('#findings details.trail', d => d.length);
  check('every principal finding has an evidence trail', nf === D.narrative.findings.length, nf);
  await page.click('#trail-0 > summary');
  const docs0 = await page.$$eval('#trail-0 .xdoc', d => d.length);
  check('trail 0 shows its passages', docs0 === D.narrative.findings[0].trail.length, docs0);
  const steps0 = await page.$$eval('#trail-0 ol li', d => d.length);
  check('trail 0 shows reasoning steps', steps0 === D.narrative.findings[0].reasoning.length, steps0);
  const hl = await page.$$eval('#trail-0 .xdoc a', a => a.filter(x => /Open at highlighted passage/.test(x.textContent)).map(x => x.href));
  check('highlight links carry text fragments', hl.length > 0 && hl.every(h => h.includes('#:~:text=')), hl.length);
  const q0 = await page.$eval('#trail-0 .xdoc blockquote', b => b.textContent);
  const x0 = D.excerpts[D.narrative.findings[0].trail[0].excerpt].quote;
  check('trail quote matches workbook excerpt', q0 === x0);
  await page.screenshot({ path: out + '/01b_trail.png', fullPage: false, clip: { x: 0, y: 300, width: 1440, height: 1400 } }).catch(()=>{});
  await page.click('#trail-0 .xdoc button.src');
  await page.waitForSelector('#srcdlg.open');
  const st = await page.$eval('#s-title', e => e.textContent);
  check('source card opens with title', st.length > 10, st.slice(0,60));
  const sp = await page.$$eval('#srccard .xdoc', d => d.length);
  check('source card lists key passages', sp >= 1, sp);
  await page.screenshot({ path: out + '/01c_sourcecard.png' });
  await page.keyboard.press('Escape');
  check('source card closes on Esc', !(await page.$('#srcdlg.open')));
  const allx = Object.values(D.excerpts);
  check('all excerpts verified or flagged', allx.every(x => /^Verified|^Not re-checked/.test(x.verification)), allx.length);
  // landscape
  await page.click('#tabs button[data-v=landscape]');
  let rows = await page.$$eval('#firm-table tbody tr', r => r.length);
  check('landscape shows all firms', rows === D.firms.length, rows);
  const names = await page.$$eval('#firm-table tbody tr button.name', b => b.map(x => x.textContent));
  check('all firm names present', D.firms.every(f => names.includes(f.name)));
  await page.click('#scope button[data-s=priority]');
  const pnames = await page.$$eval('#firm-table tbody tr button.name', b => b.map(x => x.textContent));
  const exp = D.priority.map(id => D.firms.find(f => f.id === id).name);
  check('priority shortlist matches workbook', pnames.length === exp.length && exp.every(n => pnames.includes(n)), pnames.length);
  await page.click('#scope button[data-s=all]');
  await page.click('#f-tag button[data-k=bess]');
  await page.click('#f-cls button[data-k="1"]');
  rows = await page.$$eval('#firm-table tbody tr button.name', b => b.map(x => x.textContent));
  const expC = D.firms.filter(f => f.tags.includes('bess') && f.classes.includes(1)).map(f => f.name);
  check('combined filters (BESS + class 1)', rows.length === expC.length && expC.every(n => rows.includes(n)), rows.join('|'));
  await page.click('#f-cat button[data-k=A]');
  await page.fill('#q-firm', 'enertis');
  rows = await page.$$eval('#firm-table tbody tr button.name', b => b.map(x => x.textContent));
  check('search + filters', rows.length === 1 && rows[0] === 'Enertis Applus+', rows.join('|'));
  await page.click('#clear-firm');
  rows = await page.$$eval('#firm-table tbody tr', r => r.length);
  check('clear filters restores all', rows === D.firms.length, rows);
  await page.click('#firm-table th button.sort[data-k=strength]');
  const firstStrength = await page.$eval('#firm-table tbody tr td:nth-child(7)', td => td.textContent);
  check('sort by strength asc', /^Strong/.test(firstStrength), firstStrength);
  await page.click('#firm-table th button.sort[data-k=strength]');
  const firstStrength2 = await page.$eval('#firm-table tbody tr td:nth-child(7)', td => td.textContent);
  check('sort by strength desc', /Not re-verified/.test(firstStrength2), firstStrength2);
  await page.click('#firm-table th button.sort[data-k=name]');
  await page.screenshot({ path: out + '/02_landscape.png' });
  // profile
  await page.click('#firm-table tbody tr button.name >> text="E3 Consulting"');
  await page.waitForSelector('#drawer.open'); await page.waitForTimeout(400);
  const dtitle = await page.$eval('#d-title', e => e.textContent);
  check('profile opens E3', dtitle === 'E3 Consulting');
  const dtext = await page.$eval('#d-body', e => e.innerText);
  check('profile has E3 ownership', /NAES/.test(dtext));
  check('profile lists Cross Trails evidence', /Cross Trails/.test(dtext));
  const dlinks = await page.$$eval('#d-body button.src', a => a.length);
  check('profile source links', dlinks > 3, dlinks);
  await page.screenshot({ path: out + '/03_profile.png' });
  const facts = await page.$$eval('#d-body .dsec:first-of-type .xdoc blockquote', b => b.map(x => x.textContent));
  check('E3 profile key facts quote NAES ownership', facts.some(q => /NAES Corporation/.test(q)), facts.length);
  const recs = await page.$$eval('#d-body details.rec', d => d.length);
  const e3 = D.firms.find(f => f.id === 'e3-consulting');
  check('E3 profile lists each evidence record as expandable', recs === e3.evidenceIds.length, recs + '/' + e3.evidenceIds.length);
  await page.click('#d-body details.rec > summary');
  const recq = await page.$$eval('#d-body details.rec[open] blockquote', b => b.length);
  check('profile record expands to passage', recq >= 1, recq);
  const why = await page.$eval('#d-body details.rec[open]', d => d.innerText);
  check('profile record shows classification rationale', /Why this classification/.test(why));
  await page.keyboard.press('Escape');
  check('drawer closes on Esc', !(await page.$('#drawer.open')));
  // profile of non-priority firm shows NE text
  await page.click('#firm-table tbody tr button.name >> text="Ramboll"');
  const rt = await page.$eval('#d-body', e => e.innerText);
  check('non-priority profile uses not-established text', /Not established in public research/.test(rt));
  await page.click('#d-compare');
  await page.waitForSelector('#v-mayfield.active');
  const heads = await page.$$eval('#cmp-table thead th', t => t.map(x => x.innerText));
  check('compare adds Ramboll beside Mayfield', heads.includes('Ramboll') && heads.includes('Mayfield Renewables'), heads.join('|'));
  // evidence
  await page.click('#tabs button[data-v=evidence]');
  rows = await page.$$eval('#ev-table tbody tr', r => r.length);
  check('evidence shows all records', rows === D.evidence.length, rows);
  const evlinks = await page.$$eval('#ev-table tbody a[href^="https://"]', a => a.length);
  check('evidence source links present', evlinks >= D.evidence.length, evlinks);
  await page.selectOption('#f-evfirm', 'leidos');
  rows = await page.$$eval('#ev-table tbody tr', r => r.length);
  const expL = D.evidence.filter(e => e.firmIds.includes('leidos')).length;
  check('evidence firm filter (Leidos)', rows === expL, rows + '/' + expL);
  await page.click('#f-evcls button[data-k="1"]');
  rows = await page.$$eval('#ev-table tbody tr', r => r.length);
  const expL1 = D.evidence.filter(e => e.firmIds.includes('leidos') && e.class === 1).length;
  check('evidence firm + class filter', rows === expL1, rows + '/' + expL1);
  const qual = await page.$eval('#ev-table tbody tr td:last-child', td => td.innerText);
  check('class 1 shows reliance-letter qualification', /signed reliance letter not examined/.test(qual));
  await page.click('#clear-ev');
  await page.selectOption('#f-evcp', 'MUFG');
  rows = await page.$$eval('#ev-table tbody tr', r => r.length);
  check('counterparty filter MUFG', rows > 0 && rows < D.evidence.length, rows);
  await page.selectOption('#f-evyear', '2026');
  rows = await page.$$eval('#ev-table tbody tr', r => r.length);
  check('counterparty + year', rows >= 0, rows);
  await page.click('#clear-ev');
  await page.selectOption('#f-evtype', 'BESS');
  rows = await page.$$eval('#ev-table tbody tr', r => r.length);
  check('project type filter BESS', rows === D.evidence.filter(e => e.projectType === 'BESS').length, rows);
  await page.click('#clear-ev');
  await page.click('#ev-table button.xtog');
  let xr = await page.$$eval('#ev-table tr.xrow', r => r.length);
  check('evidence row expands to passage', xr === 1, xr);
  const xq = await page.$eval('#ev-table tr.xrow', r => r.innerText);
  check('expanded record shows rationale and highlight link', /Why this classification/.test(xq) && /Open at highlighted passage|Open document/.test(xq));
  await page.click('#exp-ev');
  xr = await page.$$eval('#ev-table tr.xrow', r => r.length);
  check('expand all opens every record', xr === D.evidence.length, xr);
  const nq = await page.$$eval('#ev-table tr.xrow blockquote', b => b.length);
  const expQ = D.evidence.reduce((n, e) => n + e.excerptIds.length, 0);
  check('every record passage rendered', nq === expQ, nq + '/' + expQ);
  await page.screenshot({ path: out + '/04b_evidence_expanded.png', clip: { x: 0, y: 380, width: 1440, height: 1100 } }).catch(()=>{});
  await page.click('#exp-ev');
  await page.screenshot({ path: out + '/04_evidence.png' });
  // segments
  await page.click('#tabs button[data-v=segments]');
  const segRows = await page.$$eval('#seg-matrix tbody tr', r => r.length);
  check('7 segments', segRows === 7, segRows);
  await page.click('#seg-list button[data-seg="5"]');
  const sd = await page.$eval('#seg-detail h3', e => e.textContent);
  check('segment detail switches', /Sponsor-side/.test(sd), sd);
  await page.click('#seg-list button[data-seg="2"]');
  await page.screenshot({ path: out + '/05_segments.png', fullPage: true });
  // mayfield
  await page.click('#tabs button[data-v=mayfield]');
  await page.click('#cmp-clear');
  await page.click('#cmp-pickers button[data-id=dnv]');
  await page.click('#cmp-pickers button[data-id=luminate]');
  const h2 = await page.$$eval('#cmp-table thead th', t => t.map(x => x.innerText));
  check('compare selected firms', h2.length === 4 && h2.includes('DNV') && h2.includes('Luminate'), h2.join('|'));
  await page.screenshot({ path: out + '/06_mayfield.png', fullPage: true });
  // findings
  await page.click('#tabs button[data-v=findings]');
  const aud = await page.$$eval('#aud-table tbody tr', r => r.length);
  check('audit rows', aud === D.audit.length, aud);
  const src = await page.$$eval('#src-table tbody tr', r => r.length);
  check('source rows', src === Object.keys(D.sources).length, src);
  await page.click('#f-aud button:nth-child(3)');
  const aud2 = await page.$$eval('#aud-table tbody tr', r => r.length);
  check('audit filter not found', aud2 > 0 && aud2 < D.audit.length, aud2);
  await page.screenshot({ path: out + '/07_findings.png' });
  // text scan
  const all = await page.evaluate(() => document.body.innerText);
  check('no placeholder text', !/\blorem\b|\bplaceholder\b|\bTODO\b|\bundefined\b|\bNaN\b|\[object/.test(all));
  // tablet + mobile
  for (const [w,h,n] of [[820,1180,'tablet'],[390,844,'mobile']]) {
    const p2 = await browser.newPage({ viewport: { width: w, height: h } });
    p2.on('pageerror', e => errors.push(n + ' pageerror: ' + e.message));
    await p2.goto(file + '#landscape');
    await p2.screenshot({ path: `${out}/08_${n}_landscape.png` });
    await p2.goto(file + '#overview'); await p2.reload();
    await p2.screenshot({ path: `${out}/09_${n}_overview.png` });
    const ow = await p2.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    check(`${n}: no page-level horizontal overflow`, ow <= 1, ow);
    await p2.close();
  }
  check('every evidence record has a passage', D.evidence.every(e => e.excerptIds.length > 0));
  check('every priority firm has key-fact passages', D.priority.every(id => D.firms.find(f => f.id === id).factIds.length > 0));
  check('no JS errors', errors.length === 0, errors.join(' || '));
  check('no network requests (offline-capable)', reqs.length === 0, reqs.join(','));
  console.log(results.join('\n'));
  await browser.close();
})();
